    // What the generic twins below ask of T. float is the only type in zerocore
    // that has it, so Tensor.Sum<float>(t) compiles and Tensor.Sum<double>(t)
    // doesn't: "There is no boxing conversion from 'double' to
    // 'IFloatTensorElement'". (.NET asks for generic math interfaces such as
    // IAdditionOperators<T, T, T>, which zerocore doesn't have.)
    public interface IFloatTensorElement { }

    // .NET's Tensor methods are generic (Tensor.Sum<T>, where T is any number
    // type); zerocore's math is for float only. Each float method has a generic
    // twin here, with .NET's name and parameters, so that code written for .NET
    // (Tensor.Sum<float>(tensor), where C# can't infer T through the conversion
    // to ReadOnlyTensorSpan<T>) compiles unchanged. A twin takes only a T that
    // is an IFloatTensorElement, so another element type is a compile error;
    // it forwards to the float method, and (should a struct of the program's
    // implement the interface) ends the program with NotSupportedException
    // for any T but float. Generated by scripts/tensor-twins.py.
    public static partial class Tensor
    {
        private static class FloatOnly<T>
        {
            private static readonly bool s_isFloat = typeof(T) == typeof(float);

            public static void Check()
            {
                if (!s_isFloat)
                    throw new NotSupportedException("zerocore's Tensor math is for float tensors only.");
            }
        }

        private static ref readonly ReadOnlyTensorSpan<float> AsFloat<T>(ref readonly ReadOnlyTensorSpan<T> x)
            => ref Unsafe.As<ReadOnlyTensorSpan<T>, ReadOnlyTensorSpan<float>>(ref Unsafe.AsRef(in x));

        private static ref readonly TensorSpan<float> AsFloat<T>(ref readonly TensorSpan<T> x)
            => ref Unsafe.As<TensorSpan<T>, TensorSpan<float>>(ref Unsafe.AsRef(in x));

        private static float AsFloat<T>(T value) => Unsafe.As<T, float>(ref value);

        private static T FromFloat<T>(float value) => Unsafe.As<float, T>(ref value);

        public static Tensor<bool> Equals<T>(in ReadOnlyTensorSpan<T> x, in ReadOnlyTensorSpan<T> y)
            where T : IFloatTensorElement
        {
            FloatOnly<T>.Check();
            return Equals(in AsFloat(in x), in AsFloat(in y));
        }

