// Writes zerocore/System/Globalization/UnicodeData.cs: what char and
// CharUnicodeInfo need to answer as .NET does, read from the .NET this tool
// runs on (net10.0, which has Unicode 16.0).
//
//   dotnet run --project scripts/gen-unicode              rewrite the file
//   dotnet run --project scripts/gen-unicode -- --check   print the checksums
//                                                         samples/Chars.cs expects
//
// Three tables, so a program links only the ones it uses: every code point's
// category; each char's distance to its upper and lower case (the simple,
// invariant mapping of char.ToUpperInvariant); every code point's numeric
// value. Each is a four-level lookup whose block sizes are chosen here to make
// it smallest. Encoding.Latin1's replacements for chars above U+00FF ("best
// fit": Ā becomes A) are listed too.

using System.Globalization;
using System.Text;

if (args.Contains("--check"))
{
    Checksums.Print();
    return;
}

const int CodePoints = 0x110000;

var categories = new int[CodePoints];
var numberOf = new int[CodePoints];
var numbers = new List<double> { -1 };
for (int cp = 0; cp < CodePoints; cp++)
{
    string text = cp is >= 0xD800 and <= 0xDFFF ? ((char)cp).ToString() : char.ConvertFromUtf32(cp);
    categories[cp] = (int)CharUnicodeInfo.GetUnicodeCategory(text, 0);
    double numeric = CharUnicodeInfo.GetNumericValue(text, 0);
    int index = numbers.IndexOf(numeric);
    if (index < 0)
    {
        index = numbers.Count;
        numbers.Add(numeric);
    }
    numberOf[cp] = index;
}

// Casing, for chars: the distance to the upper and lower case, modulo 65536
// (U+019B's upper case is U+A7DC, 42561 away).
var casings = new List<(int Upper, int Lower)> { (0, 0) };
var casingOf = new int[0x10000];
for (int c = 0; c <= 0xFFFF; c++)
{
    var pair = ((char.ToUpperInvariant((char)c) - c) & 0xFFFF, (char.ToLowerInvariant((char)c) - c) & 0xFFFF);
    int index = casings.IndexOf(pair);
    if (index < 0)
    {
        index = casings.Count;
        casings.Add(pair);
    }
    casingOf[c] = index;
}

// Casing above U+FFFF (Deseret, Osage, Adlam, ...), as Rune.ToUpperInvariant
// and string casing see it: runs of code points with the same distances to
// their upper and lower case.
var wide = new List<byte>();
int wideRuns = 0;
for (int cp = 0x10000; cp < CodePoints; )
{
    int up = Rune.ToUpperInvariant(new Rune(cp)).Value - cp, low = Rune.ToLowerInvariant(new Rune(cp)).Value - cp;
    if (up == 0 && low == 0)
    {
        cp++;
        continue;
    }
    int end = cp + 1;
    while (end < CodePoints && Rune.ToUpperInvariant(new Rune(end)).Value - end == up
        && Rune.ToLowerInvariant(new Rune(end)).Value - end == low)
        end++;
    int length = end - cp;
    wide.AddRange([(byte)cp, (byte)(cp >> 8), (byte)(cp >> 16), (byte)length, (byte)(length >> 8),
        (byte)up, (byte)(up >> 8), (byte)low, (byte)(low >> 8)]);
    wideRuns++;
    cp = end;
}

// Latin-1's best fit: every char above U+00FF that Encoding.Latin1 turns into
// something other than '?'.
var bestFit = new List<byte>();
for (int c = 0x100; c <= 0xFFFF; c++)
{
    if (c is >= 0xD800 and <= 0xDFFF)
        continue;
    byte[] bytes = Encoding.Latin1.GetBytes(((char)c).ToString());
    if (bytes.Length != 1)
        throw new Exception($"Latin1 gives {bytes.Length} bytes for U+{c:X}");
    if (bytes[0] != (byte)'?')
        bestFit.AddRange([(byte)c, (byte)(c >> 8), bytes[0]]);
}

var sb = new StringBuilder();
sb.Append($$"""
// <auto-generated>
// Written by scripts/gen-unicode from .NET {{Environment.Version}}'s Unicode data.
// Don't edit; rerun: dotnet run --project scripts/gen-unicode
// </auto-generated>

namespace System.Globalization
{
    internal static partial class UnicodeData
    {

""");
int total = 0;
total += Trie(sb, "Category", categories, "Every code point's UnicodeCategory.");
total += Trie(sb, "Casing", casingOf, "Each char's index in CasingPairs.");
var casingBytes = new List<byte>();
foreach (var (upper, lower) in casings)
    casingBytes.AddRange([(byte)upper, (byte)(upper >> 8), (byte)lower, (byte)(lower >> 8)]);
total += Emit(sb, "CasingPairs", casingBytes,
    "Distance to the upper case, then to the lower case: 2 bytes each,\n        // little-endian, modulo 65536.");
total += Emit(sb, "WideCasing", wide,
    "Casing above U+FFFF: runs of a first code point (3 bytes), a length (2 bytes),\n        // and the signed distances to the upper and the lower case (2 bytes each),\n        // little-endian, sorted.");
total += Trie(sb, "Number", numberOf, "Every code point's index in Numbers.");
var numberBytes = new List<byte>();
foreach (double n in numbers)
{
    long bits = BitConverter.DoubleToInt64Bits(n);
    for (int i = 0; i < 8; i++)
        numberBytes.Add((byte)(bits >> (8 * i)));
}
total += Emit(sb, "Numbers", numberBytes, "Numeric values, as the bits of doubles, little-endian. The first, -1, is none.");
total += Emit(sb, "Latin1BestFit", bestFit,
    "Encoding.Latin1's best fit: a char (2 bytes, little-endian) and the byte it\n        // becomes, sorted by char.");
sb.Append("    }\n}\n");

string path = Path.Combine(FindRoot(), "zerocore/System/Globalization/UnicodeData.cs");
File.WriteAllText(path, sb.ToString());
Console.WriteLine($"{path}: {total} bytes of tables ({casings.Count} casings, {wideRuns} wide casing runs, {numbers.Count} numbers, {bestFit.Count / 3} best-fit chars)");

// A four-level table over values. The lowest level holds the values in
// blocks of 1 << Bits4; each level above holds, in blocks of its own size,
// the numbers of blocks in the level below; level 1 is indexed by the code
// point's high bits. A block that repeats is stored once. Writes the table
// with the block sizes that make it smallest; returns its size.
static int Trie(StringBuilder sb, string name, int[] values, string comment)
{
    (int Size, int[] Bits, List<int[]> Levels, int[] Widths)? best = null;
    for (int b4 = 2; b4 <= 8; b4++)
    for (int b3 = 2; b3 <= 8; b3++)
    for (int b2 = 2; b2 <= 8; b2++)
    {
        int[] bits = [b2, b3, b4];
        var (levels, widths, size) = Build(values, bits);
        if (best is null || size < best.Value.Size)
            best = (size, bits, levels, widths);
    }
    var t = best!.Value;
    sb.Append($"        // {comment}\n");
    sb.Append($"        // {string.Join(" + ", t.Levels.Select(l => l.Length))} entries, {t.Size} bytes.\n");
    for (int i = 0; i < 3; i++)
        sb.Append($"        private const int {name}Bits{i + 2} = {t.Bits[i]};\n");
    for (int i = 0; i < 4; i++)
        sb.Append($"        private const int {name}Width{i + 1} = {t.Widths[i]};\n");
    sb.Append('\n');
    for (int i = 0; i < 4; i++)
        Emit(sb, $"{name}Level{i + 1}", Bytes(t.Levels[i], t.Widths[i]), null);
    return t.Size;
}

// bits: the block sizes of levels 2, 3 and 4. Returns levels 1 to 4, the
// width of each one's entries (1 or 2 bytes), and their total size.
static (List<int[]> Levels, int[] Widths, int Size) Build(int[] values, int[] bits)
{
    var levels = new List<int[]>();
    var widths = new List<int>();
    int[] current = values;
    int width = Width(values.Max() + 1);
    for (int level = 2; level >= 0; level--)
    {
        int size = 1 << bits[level];
        var blocks = new Dictionary<string, int>();
        var stored = new List<int>();
        var index = new int[current.Length / size];
        for (int block = 0; block < index.Length; block++)
        {
            var slice = current.AsSpan(block * size, size).ToArray();
            string key = string.Join(",", slice);
            if (!blocks.TryGetValue(key, out int number))
            {
                number = blocks.Count;
                blocks[key] = number;
                stored.AddRange(slice);
            }
            index[block] = number;
        }
        levels.Insert(0, stored.ToArray());
        widths.Insert(0, width);
        width = Width(blocks.Count);
        current = index;
    }
    levels.Insert(0, current);
    widths.Insert(0, width);
    int total = 0;
    for (int i = 0; i < 4; i++)
        total += levels[i].Length * widths[i];
    return (levels, widths.ToArray(), total);
}

static int Width(int count) => count <= 256 ? 1 : 2;

static List<byte> Bytes(int[] values, int width)
{
    var bytes = new List<byte>();
    foreach (int v in values)
    {
        bytes.Add((byte)v);
        if (width == 2)
            bytes.Add((byte)(v >> 8));
    }
    return bytes;
}

static int Emit(StringBuilder sb, string name, List<byte> bytes, string? comment)
{
    if (comment != null)
        sb.Append($"        // {comment}\n");
    sb.Append($"        internal static ReadOnlySpan<byte> {name} =>\n        [");
    for (int i = 0; i < bytes.Count; i++)
    {
        if (i % 16 == 0)
            sb.Append("\n            ");
        sb.Append($"0x{bytes[i]:X2}");
        if (i != bytes.Count - 1)
            sb.Append(i % 16 == 15 ? "," : ", ");
    }
    sb.Append("\n        ];\n\n");
    return bytes.Count;
}

static string FindRoot()
{
    var dir = new DirectoryInfo(AppContext.BaseDirectory);
    while (dir != null && !Directory.Exists(Path.Combine(dir.FullName, "zerocore")))
        dir = dir.Parent;
    return dir?.FullName ?? throw new Exception("zerocore/ not found above " + AppContext.BaseDirectory);
}
